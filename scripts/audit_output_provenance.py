#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Which outputs/* artifacts have no generator script?

Three times in this session an artifact was stale because nothing produced it:

  * the submission package's figures -- `if not d.exists()` meant they never
    refreshed after the first build;
  * Table 2 -- no generator at all, so a regrade left it printing `high | A` for
    two rules that had become `medium | B`, including in the copy a reviewer
    would read;
  * the README -- hand-maintained prose that had drifted to claiming `outputs/`
    was empty and the arbiter deterministic.

Each was found by accident, while looking for something else. The common property
is that the artifact has no executable link to its source, so nothing fails when
the source moves.

This enumerates every file under `outputs/` and asks, for each, whether some
script in `scripts/` or `app/` names it. A file no script names is either
hand-maintained (and will drift) or generated by something that writes its name
dynamically -- both worth knowing about.

It reports; it does not fix. Deciding what to do about each is a judgement call.

Run: python scripts/audit_output_provenance.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "outputs" / "agent" / "output_provenance.json"

# Directories whose contents are bulk/derived and not individually interesting.
SKIP_DIRS = {"archive_v1.1", "archive_v1.2_preR5", "_journal_pages",
             "lightrag_index"}
SKIP_EXT = {".tiff", ".png", ".svg", ".pdf", ".zip", ".log"}


def main() -> int:
    scripts = []
    for base in ("scripts", "app", "src"):
        for p in (ROOT / base).rglob("*.py"):
            if any(s in p.parts for s in ("__pycache__",)):
                continue
            scripts.append((p, p.read_text(encoding="utf-8", errors="replace")))

    out_root = ROOT / "outputs"
    artifacts, orphan = [], []
    for f in sorted(out_root.rglob("*")):
        if not f.is_file():
            continue
        if f.suffix.lower() in SKIP_EXT:
            continue
        rel = f.relative_to(ROOT).as_posix()
        if any(s in f.parts for s in SKIP_DIRS):
            continue
        if f.name == "output_provenance.json":
            continue

        # A script "owns" the file if it names the file, or names its parent
        # directory together with the stem -- the latter catches loops that build
        # paths from parts.
        stem = f.stem
        parent = f.parent.name
        owners = []
        for sp, text in scripts:
            if f.name in text:
                owners.append(sp.relative_to(ROOT).as_posix())
                continue
            if parent in text and stem in text and "glob" in text:
                owners.append(sp.relative_to(ROOT).as_posix())
        rec = {"artifact": rel, "generators": owners}
        artifacts.append(rec)
        if not owners:
            orphan.append(rec)

    total = len(artifacts)
    print(f"outputs/ artifacts examined : {total}")
    print(f"  named by some script      : {total - len(orphan)}")
    print(f"  NO script names it        : {len(orphan)}")
    print()
    if orphan:
        print("Artifacts no script mentions (hand-maintained, or written by a")
        print("dynamically-built name -- both drift silently when their source")
        print("changes):")
        by_dir: dict[str, list[str]] = {}
        for o in orphan:
            by_dir.setdefault(str(Path(o["artifact"]).parent), []).append(
                Path(o["artifact"]).name)
        for d, names in sorted(by_dir.items()):
            print(f"  {d}/  ({len(names)})")
            for n in sorted(names)[:6]:
                print(f"      {n}")
            if len(names) > 6:
                print(f"      ... and {len(names) - 6} more")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"examined": total,
                               "without_named_generator": orphan,
                               "all": artifacts},
                              ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\n-> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
