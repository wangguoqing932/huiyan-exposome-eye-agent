#!/usr/bin/env python
"""R10 (2026-10-15): baseline full_system F1 bootstrap CI — canonical generator.

审计修复:outputs/baseline_fullsystem_bootstrap_ci.json 此前由一次性 ad-hoc 命令
生成,仓库内无脚本(审计 2026-10-15 发现)。本脚本以可复现方式重建该文件:
numpy default_rng(20261014) + integers 重采样 80 对索引,B=2000,百分位 2.5/97.5,
逐位复现 R5 落盘数值 [0.1176, 0.6401]。

gold 口径(修正原 note 的误导描述):survey svyglm 三态主口径,80 个 judgeable
tested 对中共 7 个 replicated 阳性(其中 5 个为规则覆盖;"5 replicated"只是
规则子集 headline 计数,不是重采样全集)。

Run: PYTHONUTF8=1 python scripts/make_baseline_bootstrap_ci.py
"""
from __future__ import annotations
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "outputs"

B = 2000
SEED = 20261014


def f1_from_counts(tp: int, fp: int, fn: int) -> float:
    pr = tp / (tp + fp) if tp + fp else 0.0
    rc = tp / (tp + fn) if tp + fn else 0.0
    return 2 * pr * rc / (pr + rc) if pr + rc else 0.0


def main() -> int:
    recs = [json.loads(l) for l in
            (OUT / "baseline_predictions.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    runs = {}  # seed -> rows
    for r in recs:
        if r.get("valid", True) and r["baseline"] == "full_system":
            runs.setdefault(r["seed"], []).append(r)
    assert runs, "no valid full_system runs in baseline_predictions.jsonl"
    # full_system 为确定性规则引擎:断言 5 个 seed 的预测逐对一致后取 seed=11 行
    base = {(r["a_flag"], r["b_item"]): r["prediction"] for r in runs[11]}
    for s, rows in runs.items():
        for r in rows:
            assert base[(r["a_flag"], r["b_item"])] == r["prediction"], \
                f"full_system seed-invariance violated at seed {s}"
    # 保持 jsonl 出现顺序(与 R5 ad-hoc 计算一致;排序会改变重采样索引映射)
    rows = runs[11]
    pred = np.array([bool(r["prediction"]) for r in rows])
    gold = np.array([r["gold3"] == "replicated" for r in rows])
    n = len(rows)

    rng = np.random.default_rng(SEED)
    boots = []
    for _ in range(B):
        idx = rng.integers(0, n, n)
        p, g = pred[idx], gold[idx]
        boots.append(f1_from_counts(int((p & g).sum()), int((p & ~g).sum()), int((~p & g).sum())))
    lo, hi = np.percentile(boots, [2.5, 97.5])
    point = f1_from_counts(int((pred & gold).sum()), int((pred & ~gold).sum()), int((~pred & gold).sum()))

    out = {
        "method": "bootstrap percentile, B=2000, seed=20261014, resampling pairs "
                  "(numpy default_rng.integers; generated by scripts/make_baseline_bootstrap_ci.py)",
        "date": "2026-10-14 (R5); canonicalized 2026-10-15 (R10 audit)",
        "gold": ("survey svyglm variance headline (7 replicated positives among 80 tested "
                 "judgeable pairs, of which 5 rule-covered; pair-level labels from "
                 "baseline_predictions.jsonl gold3)"),
        "F1_point": round(point, 4),
        "F1_ci95": [round(float(lo), 4), round(float(hi), 4)],
        "note": ("supersedes v1.2-era bootstrap (F1=0.583, freq-variance gold, 71 pairs); recall CI is "
                 "degenerate ([1,1]-like) by construction for a deterministic rule engine covering all "
                 "rule-covered replicated pairs and must be labeled as such"),
    }
    (OUT / "baseline_fullsystem_bootstrap_ci.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"[bootstrap] F1={out['F1_point']} CI=[{out['F1_ci95'][0]}, {out['F1_ci95'][1]}] "
          f"(B={B}, seed={SEED}, n={n} pairs, gold positives={int(gold.sum())})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
